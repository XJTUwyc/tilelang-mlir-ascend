@tilelang.testing.requires_package("mlir")
def test_vcvt_uint8_to_int8_emits_no_cast():
    """uint8 -> int8 is same bit-width; MLIR integers are signless so no
    cast op should be emitted (the input is yielded directly)."""
    source = _lower_to_tile_source(
        _vcvt_kernel(src_dtype="uint8", dst_dtype="int8")
    )
    block = _extract_vcvt_block(source)
    # No arith cast op should appear; the block only contains linalg.yield.
    assert "arith." not in block, (
        f"Expected no arith cast for same-width int->int.\nBlock:\n{block}"
    )
    assert "linalg.yield" in block, (
        f"Expected linalg.yield in block.\nBlock:\n{block}"
    )



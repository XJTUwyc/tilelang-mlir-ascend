@tilelang.testing.requires_package("mlir")
def test_vcvt_identity_affine_map():
    """The vcvt indexing map must be the identity ``(d0) -> (d0)`` for 1-D."""
    source = _lower_to_tile_source(
        _vcvt_kernel(src_dtype="float32", dst_dtype="float16")
    )
    # The identity map is printed as ``#map = affine_map<(d0) -> (d0)>`` at
    # module top level and referenced as ``#map`` inside the generic op.
    assert "affine_map<(d0) -> (d0)>" in source, (
        "Expected identity affine map `(d0) -> (d0)` for 1-D vcvt.\n"
        f"Source:\n{source}"
    )


